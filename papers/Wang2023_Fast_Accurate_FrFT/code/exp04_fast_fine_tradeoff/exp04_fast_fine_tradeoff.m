    end

end

fprintf('============================================================\n');
fprintf('EXP04: Fast / Fine refocusing under spatial variation\n');
fprintf('Experiment folder : %s\n', exp_dir);
fprintf('Functions folder  : %s\n', functions_dir);
fprintf('Results folder    : %s\n', results_dir);
fprintf('============================================================\n\n');

%% 1. Recover the physical baseline optimal order from EXP02
%
% We use the same controlled SAR geometry and the same azimuth-velocity
% state va = 20 m/s.
%
% The physical model is used only to determine the center order p0.
% The multi-line experiment itself is generated in normalized FrFT
% coordinates.

c = 299792458;

fc = 3e9;
lambda = c / fc;

PRF = 188;

H = 3000;
x0 = 3000;

vsar = 150;
va = 20;

Lant = 2;

R0 = hypot(H, x0);

az_beamwidth = lambda / Lant;

Tap_est = ...
    R0 * az_beamwidth / vsar;

N_phys = round(Tap_est * PRF);

if mod(N_phys, 2) == 0
    N_phys = N_phys + 1;
end

eta_phys = ...
    ((0:N_phys-1) - (N_phys-1)/2) / PRF;

eta_scale = ...
    max(abs(eta_phys)) / 4;

Ka_static = ...
    -2 * vsar^2 / ...
    (lambda * R0);

Ka_move = ...
    -2 * (vsar-va)^2 / ...
    (lambda * R0);

K_res = ...
    Ka_move - Ka_static;

kappa0 = ...
    K_res * eta_scale^2;

alpha0 = ...
    atan2(1, -kappa0);

p0 = ...
    2 * alpha0 / pi;

fprintf('Baseline derived from EXP02 azimuth-velocity case:\n');
fprintf('  R0                 = %.3f m\n', R0);
fprintf('  K_res              = %.6f Hz/s\n', K_res);
fprintf('  normalized kappa0  = %.6f\n', kappa0);
fprintf('  baseline p0        = %.6f\n\n', p0);

%% 2. Synthetic multi-azimuth-line ship
%
% Keep the signal length moderate because EXP04 requires thousands of FrFT
% evaluations when the traditional method is repeated for every line.

N = 193;

t = linspace(-4, 4, N);
u = t;

M = 21;                  % number of ship azimuth lines / range cells

line_index = 1:M;
best_idx = (M+1)/2;

% Hann aperture
w = ...
    0.5 ...
    - 0.5*cos( ...
    2*pi*(0:N-1)/(N-1));

%% 3. Ship scattering-energy envelope
%
% The central line is deliberately made the strongest line so that it
% becomes the "best azimuth line" as defined in the paper.

range_scale = 4.5;

amplitude = ...
    0.30 ...
    + 0.70 * ...
    exp( ...
    -0.5 * ...
    ((line_index-best_idx)/range_scale).^2);

% Guarantee a unique strongest line.
amplitude(best_idx) = ...
    max(amplitude) + 0.05;

%% 4. Fractional-frequency positions of ship scattering lines
%
% Different center-frequency terms make focused peaks appear at different
% fractional coordinates, producing a simple 2-D ship-like scattering
% structure rather than putting every line at exactly the same u.

f0 = ...
    linspace(-0.22, 0.22, M);

% Small deterministic nonlinearity to avoid a perfectly straight pattern.
f0 = ...
    f0 ...
    + 0.035 * ...
    sin( ...
    2*pi*(line_index-1)/(M-1));

%% 5. Fixed spatial pattern of order variation
%
% z is generated ONCE and reused for every sigma_p.
% Therefore increasing sigma_p changes only the amount of spatial
% variation, not its shape.

z = randn(1, M);

% Smooth the random pattern to resemble spatially correlated motion.
kernel = [1 2 3 2 1];
kernel = kernel / sum(kernel);

z = conv( ...
    z, ...
    kernel, ...
    'same');

% Force the strongest / best line to remain the representative center:
%
%       p_true(best_idx) = p0

z = ...
    z - z(best_idx);

% Normalize standard deviation.
if std(z) > 0
    z = z / std(z);
end

z(best_idx) = 0;

%% 6. Spatial-variation sweep
%
% sigma_p is the standard scale of optimal-order dispersion.
%
% sigma_p = 0:
%   all lines have exactly the same optimal order.
%
% Larger sigma_p:
%   increasing spatial variation.

sigma_list = [ ...
    0.0000, ...
    0.0025, ...
    0.0050, ...
    0.0100, ...
    0.0200, ...
    0.0400, ...
    0.0800];

n_sigma = numel(sigma_list);

%% 7. Noise setting

SNR_dB = 35;

fprintf('Synthetic ship configuration:\n');
fprintf('  azimuth lines M        = %d\n', M);
fprintf('  samples per line N     = %d\n', N);
fprintf('  best line index        = %d\n', best_idx);
fprintf('  SNR                    = %.1f dB\n', SNR_dB);
fprintf('  number of sigma cases  = %d\n\n', n_sigma);

%% 8. Search settings
%
% Same search steps used in EXP03 / paper:
%
%   coarse = 0.1
%   fine   = 0.005

p_bounds = [0.02, 1.98];

p_initial = 1.0;

h_coarse = 0.1;
h_fine = 0.005;

%% 9. Preallocate ALL numerical results
%
% IMPORTANT:
% We deliberately avoid struct arrays here.
% This prevents the MATLAB field-mismatch errors encountered in EXP02/03.

p_true_all = ...
    zeros(n_sigma, M);

p_best_est = ...
    zeros(n_sigma, 1);

p_fast_all = ...
    zeros(n_sigma, M);

p_fine_all = ...
    zeros(n_sigma, M);

p_trad_all = ...
    zeros(n_sigma, M);

entropy_fast_line = ...
    zeros(n_sigma, M);

entropy_fine_line = ...
    zeros(n_sigma, M);

entropy_trad_line = ...
    zeros(n_sigma, M);

concentration_fast_line = ...
    zeros(n_sigma, M);

concentration_fine_line = ...
    zeros(n_sigma, M);

concentration_trad_line = ...
    zeros(n_sigma, M);

image_entropy_fast = ...
    zeros(n_sigma, 1);

image_entropy_fine = ...
    zeros(n_sigma, 1);

image_entropy_trad = ...
    zeros(n_sigma, 1);

mean_entropy_fast = ...
    zeros(n_sigma, 1);

mean_entropy_fine = ...
    zeros(n_sigma, 1);

mean_entropy_trad = ...
    zeros(n_sigma, 1);

order_rmse_fast = ...
    zeros(n_sigma, 1);

order_rmse_fine = ...
    zeros(n_sigma, 1);

order_rmse_trad = ...
    zeros(n_sigma, 1);

calls_fast = ...
    zeros(n_sigma, 1);

calls_fine = ...
    zeros(n_sigma, 1);

calls_trad = ...
    zeros(n_sigma, 1);

runtime_fast = ...
    zeros(n_sigma, 1);

runtime_fine = ...
    zeros(n_sigma, 1);

runtime_trad = ...
    zeros(n_sigma, 1);

best_search_calls = ...
    zeros(n_sigma, 1);

% Store the largest-sigma example for visual comparison.
example_input = [];
example_fast = [];
example_fine = [];
example_trad = [];
example_p_true = [];

%% 10. Sweep sigma_p

fprintf('Starting spatial-variation sweep...\n\n');

for is = 1:n_sigma

    sigma_p = sigma_list(is);

    fprintf('------------------------------------------------------------\n');
    fprintf( ...
        'sigma_p = %.4f\n', ...
        sigma_p);

    %% ---------------------------------------------------------
    % 10.1 True optimal orders

    p_true = ...
        p0 ...
        + sigma_p * z;

    % Keep orders safely inside the FrFT interval.
    p_true = ...
        min( ...
        max(p_true, 0.08), ...
        1.92);

    p_true(best_idx) = p0;

    p_true_all(is, :) = p_true;

    %% ---------------------------------------------------------
    % 10.2 Generate the multi-line ship signal
    %
    % For a FrFT order p:
    %
    %       alpha = p*pi/2
    %
    % The chirp rate satisfying the chosen kernel convention is:
    %
    %       kappa = -cot(alpha)
    %
    % Each line:
    %
    %       x_n(t) =
    %           A_n w(t)
    %           exp(j*pi*kappa_n*t^2)
    %           exp(j*2*pi*f0_n*t)
    %           exp(j*phi_n)
    %           + noise

    X_ship = ...
        zeros(M, N);

    for im = 1:M

        alpha_true = ...
            p_true(im) * pi/2;

        kappa_true = ...
            -cot(alpha_true);

        phase0 = ...
            2*pi*rand;

        clean_line = ...
            amplitude(im) .* ...
            w .* ...
            exp( ...
            1j*pi*kappa_true*t.^2) .* ...
            exp( ...
            1j*2*pi*f0(im)*t) .* ...
            exp(1j*phase0);

        signal_power = ...
            mean(abs(clean_line).^2);

        noise_power = ...
            signal_power / ...
            (10^(SNR_dB/10));

        noise = ...
            sqrt(noise_power/2) .* ...
            ( ...
            randn(1,N) ...
            + 1j*randn(1,N));

        X_ship(im, :) = ...
            clean_line + noise;

    end

    %% ---------------------------------------------------------
    % 10.3 Identify the best azimuth line exactly as paper principle:
    %      maximum line energy.

    line_energy = ...
        sum( ...
        abs(X_ship).^2, ...
        2);

    [~, best_detected_idx] = ...
        max(line_energy);

    if best_detected_idx ~= best_idx

        warning( ...
            ['Detected best line (%d) differs from intended ', ...
             'best line (%d).'], ...
            best_detected_idx, ...
            best_idx);

    end

    x_best = ...
        X_ship(best_detected_idx, :);

    %% ---------------------------------------------------------
    % 10.4 Estimate best-line order ONCE
    %
    % This search cost is shared by both Fast and Fine.

    best_result = ...
        minimum_entropy_search( ...
        x_best, ...
        t, ...
        u, ...
        p_initial, ...
        h_coarse, ...
        h_fine, ...
        p_bounds);

    p_best = ...
        best_result.p_opt;

    p_best_est(is) = p_best;

    best_search_calls(is) = ...
        best_result.n_frft;

    fprintf( ...
        '  true best-line order      = %.6f\n', ...
        p_true(best_detected_idx));

    fprintf( ...
        '  estimated best-line order = %.6f\n', ...
        p_best);

    fprintf( ...
        '  best-line search calls    = %d\n', ...
        best_result.n_frft);

    %% =========================================================
    % 10.5 FAST METHOD
    %
    % Every line uses exactly the same p_best.
    %
    % Total FrFT cost:
    %
    %       best-line search
    %       +
    %       one refocusing FrFT for every line

    tic;

    Y_fast = ...
        zeros(M, N);

    for im = 1:M

        p_fast_all(is, im) = ...
            p_best;

        Y = ...
            frft_direct( ...
            X_ship(im, :), ...
            t, ...
            p_best, ...
            u);

        Y_fast(im, :) = ...
            Y(:).';

        entropy_fast_line(is, im) = ...
            signal_entropy(Y);

        P = abs(Y).^2;

        concentration_fast_line(is, im) = ...
            max(P) / sum(P);

    end

    runtime_fast(is) = toc;

    calls_fast(is) = ...
        best_result.n_frft ...
        + M;

    %% =========================================================
    % 10.6 FINE METHOD
    %
    % Best line:
    %       directly use p_best.
    %
    % Other lines:
    %       start at p_best and move with ONLY the fine step.
    %
    % This reproduces the important logic of the paper:
    %
    %       no full coarse search for every line.

    tic;

    Y_fine = ...
        zeros(M, N);

    fine_search_calls_total = 0;

    for im = 1:M

        if im == best_detected_idx

            p_i = p_best;

        else

            fine_result = ...
                local_entropy_search( ...
                X_ship(im, :), ...
                t, ...
                u, ...
                p_best, ...
                h_fine, ...
                p_bounds);

            p_i = ...
                fine_result.p_opt;

            fine_search_calls_total = ...
                fine_search_calls_total ...
                + fine_result.n_frft;

        end

        p_fine_all(is, im) = ...
            p_i;

        Y = ...
            frft_direct( ...
            X_ship(im, :), ...
            t, ...
            p_i, ...
            u);

        Y_fine(im, :) = ...
            Y(:).';

        entropy_fine_line(is, im) = ...
            signal_entropy(Y);

        P = abs(Y).^2;

        concentration_fine_line(is, im) = ...
            max(P) / sum(P);

    end

    runtime_fine(is) = toc;

    calls_fine(is) = ...
        best_result.n_frft ...
        + fine_search_calls_total ...
        + M;

    %% =========================================================
    % 10.7 TRADITIONAL METHOD
    %
    % Every line performs:
    %
    %       complete two-stage peak search
    %
    % followed by:
    %
    %       one refocusing FrFT.
    %
    % No struct arrays are used: each search result is kept only as a
    % temporary scalar struct.

    tic;

    Y_trad = ...
        zeros(M, N);

    trad_search_calls_total = 0;

    for im = 1:M

        trad_result = ...
            two_stage_peak_search( ...
            X_ship(im, :), ...
            t, ...
            u, ...
            h_coarse, ...
            h_fine, ...
            p_bounds);

        p_i = ...
            trad_result.p_opt;

        p_trad_all(is, im) = ...
            p_i;

        trad_search_calls_total = ...
            trad_search_calls_total ...
            + trad_result.n_frft;

        Y = ...
            frft_direct( ...
            X_ship(im, :), ...
            t, ...
            p_i, ...
            u);

        Y_trad(im, :) = ...
            Y(:).';

        entropy_trad_line(is, im) = ...
            signal_entropy(Y);

        P = abs(Y).^2;

        concentration_trad_line(is, im) = ...
            max(P) / sum(P);

    end

    runtime_trad(is) = toc;

    calls_trad(is) = ...
        trad_search_calls_total ...
        + M;

    %% ---------------------------------------------------------
    % 10.8 Quality metrics

    mean_entropy_fast(is) = ...
        mean( ...
        entropy_fast_line(is, :));

    mean_entropy_fine(is) = ...
        mean( ...
        entropy_fine_line(is, :));

    mean_entropy_trad(is) = ...
        mean( ...
        entropy_trad_line(is, :));

    image_entropy_fast(is) = ...
        global_image_entropy(Y_fast);

    image_entropy_fine(is) = ...
        global_image_entropy(Y_fine);

    image_entropy_trad(is) = ...
        global_image_entropy(Y_trad);

    order_rmse_fast(is) = ...
        sqrt( ...
        mean( ...
        ( ...
        p_fast_all(is,:) ...
        - p_true ...
        ).^2));

    order_rmse_fine(is) = ...
        sqrt( ...
        mean( ...
        ( ...
        p_fine_all(is,:) ...
        - p_true ...
        ).^2));

    order_rmse_trad(is) = ...
        sqrt( ...
        mean( ...
        ( ...
        p_trad_all(is,:) ...
        - p_true ...
        ).^2));

    fprintf( ...
        '  image entropy: Fast / Fine / Trad = %.4f / %.4f / %.4f\n', ...
        image_entropy_fast(is), ...
        image_entropy_fine(is), ...
        image_entropy_trad(is));

    fprintf( ...
        '  order RMSE   : Fast / Fine / Trad = %.5f / %.5f / %.5f\n', ...
        order_rmse_fast(is), ...
        order_rmse_fine(is), ...
        order_rmse_trad(is));

    fprintf( ...
        '  FrFT calls   : Fast / Fine / Trad = %d / %d / %d\n', ...
        calls_fast(is), ...
        calls_fine(is), ...
        calls_trad(is));

    %% ---------------------------------------------------------
    % Store the strongest spatial-variation example

    if is == n_sigma

        example_input = X_ship;
        example_fast = Y_fast;
        example_fine = Y_fine;
        example_trad = Y_trad;

        example_p_true = p_true;

    end

end

fprintf('\nSpatial-variation sweep completed.\n\n');

