%% exp04_fast_fine_tradeoff.m
% EXP04: Fast / Fine / Traditional refocusing under spatial variation
%
% Reproduction + controlled extension of:
%
%   Wang et al.,
%   "Fast and Accurate Refocusing for Moving Ships in SAR Imagery
%   Based on FrFT", Remote Sensing, 2023.
%
% -------------------------------------------------------------------------
% PAPER-SUPPORTED PART
%
% The paper assumes that under favorable sea conditions a linearly moving
% ship has highly redundant defocus information among its azimuth lines:
%
%       p_opt(n) ~= p_best
%
% Based on this property:
%
%   Traditional:
%       calculate the optimal FrFT order for every azimuth line.
%
%   Fast:
%       calculate only p_best and use it for every azimuth line.
%
%   Fine:
%       calculate p_best first, then use p_best as the initial value for
%       a local minimum-entropy refinement of every other azimuth line.
%
% -------------------------------------------------------------------------
% OUR CONTROLLED EXTENSION
%
% We introduce:
%
%       sigma_p
%
% to control the spatial dispersion of true optimal FrFT orders:
%
%       p_true(n) = p0 + sigma_p * z(n)
%
% where z(n) is a fixed normalized spatial pattern.
%
% This allows us to continuously move from:
%
%       sigma_p = 0
%           ideal linear-motion / order-redundant case
%
% to:
%
%       sigma_p large
%           increasingly spatial-variant defocus.
%
% The purpose is to study:
%
%       focus quality
%            vs
%       computational burden
%            vs
%       spatial variation.
%
% -------------------------------------------------------------------------
% IMPORTANT
%
% 1) This is a controlled signal-level reproduction/extension.
%    It does NOT claim to reproduce the exact scattering geometry of a
%    real ship.
%
% 2) Each azimuth line is generated as a normalized LFM whose true FrFT
%    optimal order is known analytically.
%
% 3) Runtime is only relative because frft_direct.m is the transparent
%    O(N^2) implementation used in EXP01-EXP03.
%
% 4) The cleaner computational metric remains:
%
%       number of FrFT evaluations.
%
% -------------------------------------------------------------------------

