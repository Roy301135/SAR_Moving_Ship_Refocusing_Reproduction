% LOCAL FUNCTION 1
% Fine refocusing search around p_best
% ========================================================================

function result = local_entropy_search( ...
    x, ...
    t, ...
    u, ...
    p_initial, ...
    h, ...
    p_bounds)

%LOCAL_ENTROPY_SEARCH
% Fine-only directional minimum-entropy search.
%
% Unlike minimum_entropy_search.m:
%
%   - there is no global coarse stage;
%   - p_best is already supplied as the initial value;
%   - only the fine step h is used.
%
% This mirrors the central computational idea of the paper's Fine approach:
%
%       use p_best as initial value
%       -> avoid coarse search for every other azimuth line.

    p_min = p_bounds(1);
    p_max = p_bounds(2);

    p0 = ...
        min( ...
        max(p_initial, p_min), ...
        p_max);

    n_frft = 0;

    %% Evaluate initial point

    E0 = evaluate_entropy(p0);

    %% First test positive direction

    h_direction = abs(h);

    p1 = ...
        p0 + h_direction;

    if p1 > p_max

        h_direction = ...
            -h_direction;

        p1 = ...
            p0 + h_direction;

    end

    if p1 < p_min || p1 > p_max

        result.p_opt = p0;
        result.entropy_opt = E0;
        result.n_frft = n_frft;

        return;

    end

    E1 = ...
        evaluate_entropy(p1);

    %% If positive direction is uphill, try negative direction

    if E1 >= E0

        h_direction = ...
            -h_direction;

        p1 = ...
            p0 + h_direction;

        if p1 < p_min || p1 > p_max

            result.p_opt = p0;
            result.entropy_opt = E0;
            result.n_frft = n_frft;

            return;

        end

        E1 = ...
            evaluate_entropy(p1);

        %% If both sides are uphill, initial point is already a local min

        if E1 >= E0

            result.p_opt = p0;
            result.entropy_opt = E0;
            result.n_frft = n_frft;

            return;

        end

    end

    %% Continue downhill

    p_current = p1;
    E_current = E1;

    while true

        p_next = ...
            p_current + h_direction;

        if p_next < p_min || p_next > p_max
            break;
        end

        E_next = ...
            evaluate_entropy(p_next);

        if E_next >= E_current
            break;
        end

        p_current = p_next;
        E_current = E_next;

    end

    result.p_opt = ...
        p_current;

    result.entropy_opt = ...
        E_current;

    result.n_frft = ...
        n_frft;

    %% Nested entropy evaluator

    function H = evaluate_entropy(p)

        Xp = ...
            frft_direct( ...
            x, ...
            t, ...
            p, ...
            u);

        H = ...
            signal_entropy(Xp);

        n_frft = ...
            n_frft + 1;

    end

end

%% ========================================================================
% LOCAL FUNCTION 2
% Global 2-D energy entropy
% ========================================================================

function H = global_image_entropy(Y)

%GLOBAL_IMAGE_ENTROPY
%
% Shannon entropy of the normalized energy distribution of the full
% multi-line refocused result:
%
%       P(m,n) = |Y(m,n)|^2
%
%       p(m,n) = P(m,n) / sum(P(:))
%
%       H = -sum p log p
%
% This follows the same general energy-concentration principle used by the
% paper for image entropy.

    power_Y = ...
        abs(Y).^2;

    total_energy = ...
        sum(power_Y(:));

    if total_energy <= 0

        H = NaN;
        return;

    end

    p = ...
        power_Y(:) / ...
        total_energy;

    p = ...
        p(p > 0);

    H = ...
        -sum( ...
        p .* log(p));

end