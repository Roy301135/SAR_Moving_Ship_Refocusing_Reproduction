%% 1. SAR parameters
params.c = 299792458;

params.fc = 3e9;
params.lambda = params.c / params.fc;

params.PRF = 188;
params.B = 150e6;

params.H = 3000;
params.Lant = 2;
params.vsar = 150;
params.Tp = 1.5e-6;

% Same controlled assumption as EXP02.
% The paper defines x0 but does not provide its numerical value
% in the simulation parameter table.
params.x0 = 3000;

params.R0 = hypot(params.H, params.x0);

% Same synthetic-aperture-duration estimate as EXP02.
params.az_beamwidth = ...
    params.lambda / params.Lant;

params.Tap_est = ...
    params.R0 * ...
    params.az_beamwidth / ...
    params.vsar;

N = round( ...
    params.Tap_est * ...
    params.PRF);

% Use an odd number of samples so eta = 0 is sampled.
if mod(N, 2) == 0
    N = N + 1;
end

N = max(N, 129);

eta = ...
    ((0:N-1) - (N-1)/2) / ...
    params.PRF;

params.N = N;
params.eta = eta;

% Toolbox-free Hann aperture.
params.window = ...
    0.5 ...
    - 0.5*cos( ...
    2*pi*(0:N-1)/(N-1));

fprintf('SAR / reproduction parameters:\n');
fprintf('  fc             = %.3f GHz\n', params.fc/1e9);
fprintf('  lambda         = %.6f m\n', params.lambda);
fprintf('  PRF            = %.3f Hz\n', params.PRF);
fprintf('  H              = %.1f m\n', params.H);
fprintf('  x0             = %.1f m\n', params.x0);
fprintf('  R0             = %.3f m\n', params.R0);
fprintf('  vsar           = %.1f m/s\n', params.vsar);
fprintf('  estimated Tap  = %.6f s\n', params.Tap_est);
fprintf('  N              = %d\n\n', N);

%% 2. Motion states
motions(1) = struct( ...
    'short_name', 'Azimuth velocity', ...
    'label', 'v_a = 20 m/s', ...
    'vr', 0, ...
    'ar', 0, ...
    'va', 20, ...
    'aa', 0);

motions(2) = struct( ...
    'short_name', 'Range acceleration', ...
    'label', 'a_r = 10 m/s^2', ...
    'vr', 0, ...
    'ar', 10, ...
    'va', 0, ...
    'aa', 0);

n_cases = numel(motions);

%% 3. Generate residual signals
fprintf('Generating residual signals...\n');

signals(1) = ...
    simulate_motion_case( ...
    params, motions(1));

signals = ...
    repmat( ...
    signals(1), ...
    1, ...
    n_cases);

for ic = 2:n_cases

    signals(ic) = ...
        simulate_motion_case( ...
        params, motions(ic));

end

fprintf('Residual signals generated.\n\n');

%% 4. FrFT normalized coordinates
%
% Same normalization convention as EXP02.
%
% Physical slow time eta is mapped to normalized t in [-4,4].

t_norm = ...
    eta / ...
    max(abs(eta)) * 4;

u_norm = t_norm;

eta_scale = ...
    max(abs(eta)) / 4;

%% 5. Theoretical FrFT orders from second-order SAR model
%
% Static-target azimuth Doppler rate:
%
%   Ka_static = -2*vsar^2 / (lambda*R0)
%
% Moving-target second-order Doppler rate:
%
%   Ka_move =
%       2[-ar*x0-(vsar-va)^2] / (lambda*R0)
%
% Residual:
%
%   K_res = Ka_move - Ka_static
%
% Under the normalized coordinate t_norm:
%
%   kappa_norm = K_res * eta_scale^2
%
% and
%
%   cot(alpha_opt) + kappa_norm = 0.

Ka_static = ...
    -2 * params.vsar^2 / ...
    (params.lambda * params.R0);

p_theory = ...
    zeros(n_cases, 1);

K_res = ...
    zeros(n_cases, 1);

for ic = 1:n_cases

    ar = motions(ic).ar;
    va = motions(ic).va;

    Ka_move = ...
        2 * ...
        (-ar*params.x0 ...
        - (params.vsar-va)^2) / ...
        (params.lambda * params.R0);

    K_res(ic) = ...
        Ka_move - Ka_static;

    kappa_norm = ...
        K_res(ic) * ...
        eta_scale^2;

    alpha_opt = ...
        atan2( ...
        1, ...
        -kappa_norm);

    p_theory(ic) = ...
        2 * alpha_opt / pi;

end

%% 6. Search settings
%
% Paper:
%   coarse step = 0.1
%   fine step   = 0.005
%
% FrFT order p is periodic with period 4.
% The current useful interval is approximately 0 < p < 2.

p_bounds = [0.02, 1.98];

p_initial = 1.0;

h_coarse = 0.1;
h_fine = 0.005;

fprintf('Search parameters:\n');
fprintf('  initial order = %.3f\n', p_initial);
fprintf('  coarse step   = %.3f\n', h_coarse);
fprintf('  fine step     = %.3f\n', h_fine);
fprintf( ...
    '  search bounds = [%.2f, %.2f]\n\n', ...
    p_bounds(1), ...
    p_bounds(2));

%% 7. Run proposed and traditional searches
%
% IMPORTANT:
% MATLAB struct arrays require every element to have exactly the same fields.
%
% Therefore:
%
%   1) first build a COMPLETE temporary structure prop_i / trad_i;
%   2) add runtime, X_opt, entropy and concentration;
%   3) only then initialize the struct array using Case 1 as template.

fprintf('Starting search comparison...\n\n');

for ic = 1:n_cases

    fprintf('------------------------------------------------------------\n');
    fprintf( ...
        'Case %d: %s (%s)\n', ...
        ic, ...
        motions(ic).short_name, ...
        motions(ic).label);

    fprintf( ...
        'Theoretical order = %.6f\n\n', ...
        p_theory(ic));

    x = signals(ic).residual_signal;

    %% ---------------------------------------------------------
    % Proposed minimum-entropy search

    tic;

    prop_i = ...
        minimum_entropy_search( ...
        x, ...
        t_norm, ...
        u_norm, ...
        p_initial, ...
        h_coarse, ...
        h_fine, ...
        p_bounds);

    prop_i.runtime = toc;

    %% ---------------------------------------------------------
    % Traditional two-stage peak traversal

    tic;

    trad_i = ...
        two_stage_peak_search( ...
        x, ...
        t_norm, ...
        u_norm, ...
        h_coarse, ...
        h_fine, ...
        p_bounds);

    trad_i.runtime = toc;

    %% ---------------------------------------------------------
    % Evaluate final FrFT outputs

    X_prop = ...
        frft_direct( ...
        x, ...
        t_norm, ...
        prop_i.p_opt, ...
        u_norm);

    X_trad = ...
        frft_direct( ...
        x, ...
        t_norm, ...
        trad_i.p_opt, ...
        u_norm);

    P_prop = abs(X_prop).^2;
    P_trad = abs(X_trad).^2;

    %% Complete proposed result structure

    prop_i.X_opt = X_prop;

    prop_i.final_entropy = ...
        signal_entropy(X_prop);

    prop_i.concentration = ...
        max(P_prop) / ...
        sum(P_prop);

    %% Complete traditional result structure

    trad_i.X_opt = X_trad;

    trad_i.final_entropy = ...
        signal_entropy(X_trad);

    trad_i.concentration = ...
        max(P_trad) / ...
        sum(P_trad);

    %% ---------------------------------------------------------
    % Struct-array initialization
    %
    % Only here do the temporary structures contain every field
    % required by all subsequent cases.

    if ic == 1

        proposed = ...
            repmat( ...
            prop_i, ...
            1, ...
            n_cases);

        traditional = ...
            repmat( ...
            trad_i, ...
            1, ...
            n_cases);

    else

        proposed(ic) = prop_i;
        traditional(ic) = trad_i;

    end

    %% ---------------------------------------------------------
    % Console output

    fprintf('PROPOSED minimum entropy:\n');

    fprintf( ...
        '  p_opt         = %.6f\n', ...
        proposed(ic).p_opt);

    fprintf( ...
        '  error         = %.6e\n', ...
        abs( ...
        proposed(ic).p_opt ...
        - p_theory(ic)));

    fprintf( ...
        '  FrFT calls    = %d\n', ...
        proposed(ic).n_frft);

    fprintf( ...
        '  runtime       = %.6f s\n', ...
        proposed(ic).runtime);

    fprintf( ...
        '  entropy       = %.6f\n', ...
        proposed(ic).final_entropy);

    fprintf( ...
        '  concentration = %.6f\n\n', ...
        proposed(ic).concentration);

    fprintf('TRADITIONAL two-stage peak search:\n');

    fprintf( ...
        '  p_opt         = %.6f\n', ...
        traditional(ic).p_opt);

    fprintf( ...
        '  error         = %.6e\n', ...
        abs( ...
        traditional(ic).p_opt ...
        - p_theory(ic)));

    fprintf( ...
        '  FrFT calls    = %d\n', ...
        traditional(ic).n_frft);

    fprintf( ...
        '  runtime       = %.6f s\n', ...
        traditional(ic).runtime);

    fprintf( ...
        '  entropy       = %.6f\n', ...
        traditional(ic).final_entropy);

    fprintf( ...
        '  concentration = %.6f\n\n', ...
        traditional(ic).concentration);

end

fprintf('Search comparison completed.\n\n');

