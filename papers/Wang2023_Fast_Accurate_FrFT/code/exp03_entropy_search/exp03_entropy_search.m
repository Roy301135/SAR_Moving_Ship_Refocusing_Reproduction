%% exp03_entropy_search.m
% EXP03: Minimum-entropy advance-and-retreat search
%
% Reproduction target:
%   Wang et al., "Fast and Accurate Refocusing for Moving Ships in SAR
%   Imagery Based on FrFT", Remote Sensing, 2023.
%
% Purpose
% -------------------------------------------------------------------------
% Compare:
%
%   Method 1: Traditional two-stage FrFT peak traversal
%             - coarse traversal over the whole order interval
%             - local fine traversal around the coarse peak
%
%   Method 2: Proposed minimum-entropy advance-and-retreat search
%             - move only in the entropy-decreasing direction
%             - coarse search first
%             - local fine search second
%
% Motion cases:
%   A. Azimuth velocity    va = 20 m/s
%   B. Range acceleration ar = 10 m/s^2
%
% Both were verified in EXP02 to produce second-order residual phase / LFM.
%
% Required functions:
%   frft_direct.m
%   signal_entropy.m
%   simulate_motion_case.m
%   minimum_entropy_search.m
%   two_stage_peak_search.m
%
% IMPORTANT
% -------------------------------------------------------------------------
% Absolute runtime is NOT directly comparable with the paper because
% frft_direct.m is an O(N^2) transparent implementation used for mechanism
% verification.
%
% The meaningful quantities in EXP03 are:
%
%   1) optimal-order accuracy;
%   2) number of FrFT evaluations;
%   3) relative runtime reduction;
%   4) final focusing quality.
%
% -------------------------------------------------------------------------

