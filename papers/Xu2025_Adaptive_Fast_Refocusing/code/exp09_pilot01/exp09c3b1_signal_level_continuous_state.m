    used = min(max(budgets(ib),0),benefit_rate);

    actual_trigger_rate(ib) = used;
    policy_recall(ib) = cheap_recall+used;

    if benefit_rate>0
        beneficial_capture(ib) = min(1,used/benefit_rate);
    end

    if used>0
        benefit_precision(ib) = 1;
    end

    normalized_q_search_budget(ib) = 1+used;
end

C = table( ...
    target_budget,actual_trigger_rate,policy_recall, ...
    beneficial_capture,benefit_precision, ...
    harmful_fraction_among_triggers, ...
    normalized_q_search_budget);

end

%% ========================================================================
function C = random_expected_curve(Ttest,budgets)

budgets = budgets(:);

cheap_recall = mean(Ttest.cheap_success);
benefit_rate = mean(Ttest.beneficial);
harm_rate = mean(Ttest.harmful);

target_budget = budgets;
actual_trigger_rate = budgets;

policy_recall = ...
    cheap_recall + ...
    budgets*(benefit_rate-harm_rate);

beneficial_capture = budgets;

benefit_precision = ...
    repmat(benefit_rate,numel(budgets),1);

harmful_fraction_among_triggers = ...
    repmat(harm_rate,numel(budgets),1);

benefit_precision(budgets==0) = NaN;
harmful_fraction_among_triggers(budgets==0) = NaN;

normalized_q_search_budget = 1+budgets;

C = table( ...
    target_budget,actual_trigger_rate,policy_recall, ...
    beneficial_capture,benefit_precision, ...
    harmful_fraction_among_triggers, ...
    normalized_q_search_budget);

end

%% ========================================================================
function D = jump_diagnostics(T,cfg,H)

score_vars = {'instant_score','ema_score','reset_score'};
labels = {'InstantPE','EMA','EMAReset'};

P = numel(score_vars);

policy = cell(P,1);
mean_post_jump_state_abs_error = nan(P,1);
mean_global_state_abs_error = nan(P,1);
mean_score_change_at_jump = nan(P,1);
reset_rate_near_jump = nan(P,1);

jump_line = max(2,min(cfg.num_lines,round(cfg.jump_fraction*cfg.num_lines)));

for ip = 1:P
    policy{ip} = labels{ip};

    score = double(T.(score_vars{ip}));
    score = score(:);

    target = double(T.state_utility_norm);
    target = target(:);

    mask_post = ...
        T.line_index>=jump_line & ...
        T.line_index<=min(cfg.num_lines,jump_line+H-1);

    mean_post_jump_state_abs_error(ip) = ...
        mean(abs(score(mask_post)-target(mask_post)),'omitnan');

    mean_global_state_abs_error(ip) = ...
        mean(abs(score-target),'omitnan');

    seqs = unique(T.sequence_id).';
    jump_change = nan(numel(seqs),1);

    for is = 1:numel(seqs)
        s = seqs(is);

        i0 = find( ...
            T.sequence_id==s & ...
            T.line_index==jump_line,1,'first');

        im = find( ...
            T.sequence_id==s & ...
            T.line_index==jump_line-1,1,'first');

        if ~isempty(i0) && ~isempty(im)
            jump_change(is) = abs(score(i0)-score(im));
        end
    end

    mean_score_change_at_jump(ip) = ...
        mean(jump_change,'omitnan');

    if strcmp(score_vars{ip},'reset_score') && ...
            ismember('reset_event',T.Properties.VariableNames)

        mask_reset = ...
            T.line_index>=max(1,jump_line-1) & ...
            T.line_index<=min(cfg.num_lines,jump_line+H-1);

        reset_rate_near_jump(ip) = ...
            mean(T.reset_event(mask_reset));
    end
end

D = table( ...
    policy,mean_post_jump_state_abs_error, ...
    mean_global_state_abs_error, ...
    mean_score_change_at_jump, ...
    reset_rate_near_jump);

end

%% ========================================================================
function auc = binary_auc(y,score)

y = logical(y(:));
score = double(score(:));

valid = isfinite(score);
y = y(valid);
score = score(valid);

nPos = sum(y);
nNeg = sum(~y);

if nPos==0 || nNeg==0
    auc = NaN;
    return;
end

r = average_ranks(score);
sumPos = sum(r(y));

auc = ...
    (sumPos - nPos*(nPos+1)/2) / ...
    (nPos*nNeg);

end

%% ========================================================================
function rho = spearman_manual(x,y)

x = double(x(:));
y = double(y(:));

valid = isfinite(x) & isfinite(y);

x = x(valid);
y = y(valid);

if numel(x)<3
    rho = NaN;
    return;
end

rx = average_ranks(x);
ry = average_ranks(y);

C = corrcoef(rx,ry);

if numel(C)<4
    rho = NaN;
else
    rho = C(1,2);
end

end

%% ========================================================================
function r = average_ranks(x)

x = double(x(:));

[xs,ord] = sort(x);
rs = nan(size(xs));

i = 1;

while i<=numel(xs)
    j = i;

    while j<numel(xs) && xs(j+1)==xs(i)
        j = j+1;
    end

    rs(i:j) = (i+j)/2;
    i = j+1;
end

r = nan(size(x));
r(ord) = rs;

end

%% ========================================================================
function q = empirical_quantile(x,p)

x = double(x(:));
x = x(isfinite(x));

if isempty(x)
    q = NaN;
    return;
end

x = sort(x);

p = min(max(double(p),0),1);

if numel(x)==1
    q = x(1);
    return;
end

pos = 1+p*(numel(x)-1);

lo = floor(pos);
hi = ceil(pos);

if lo==hi
    q = x(lo);
else
    w = pos-lo;
    q = (1-w)*x(lo)+w*x(hi);
end

if ~isscalar(q)
    error('empirical_quantile must return a scalar.');
end

end

%% ========================================================================
function v = scalar_unique(x,label)

x = double(x(:));
x = x(isfinite(x));

if isempty(x)
    error('No finite values for %s.',label);
end

v = x(1);

if any(abs(x-v)>1e-12)
    error('%s is not constant.',label);
end

end

