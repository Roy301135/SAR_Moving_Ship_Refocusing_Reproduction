%% ========================================================================
function y = moving_average_shrink(x,w)
x = double(x(:));
w = max(1,round(w));

N = numel(x);
y = nan(N,1);

left = floor((w-1)/2);
right = w-1-left;

for i = 1:N
    i1 = max(1,i-left);
    i2 = min(N,i+right);

    vals = x(i1:i2);
    y(i) = mean(vals,'omitnan');
end
end

