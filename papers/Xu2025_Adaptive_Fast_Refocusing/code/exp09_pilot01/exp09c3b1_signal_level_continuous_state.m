%% ========================================================================
function T = add_instant_score(T,calib)

N = height(T);
score = nan(N,1);

for i = 1:N
    p = double(T.cheap_prominence(i));
    e = double(T.cheap_entropy(i));

    Fp = empirical_cdf_value(calib.prom_sorted,p);
    Fe = empirical_cdf_value(calib.ent_sorted,e);

    risk_prom = 1-Fp;
    risk_ent = Fe;

    score(i) = 0.5*(risk_prom+risk_ent);
end

T.instant_score = min(max(score,0),1);

end

%% ========================================================================
function F = empirical_cdf_value(sorted_x,x)

sorted_x = double(sorted_x(:));

if isempty(sorted_x)
    F = 0.5;
    return;
end

if ~isfinite(x)
    F = 0.5;
    return;
end

N = numel(sorted_x);

nLess = sum(sorted_x<x);
nEq = sum(sorted_x==x);

F = (nLess+0.5*nEq)/N;
F = min(max(F,0),1);

if ~isscalar(F)
    error('empirical_cdf_value must return a scalar.');
end

end

%% ========================================================================
function Tout = apply_history(Tin,alpha,reset_threshold)

if alpha<=0 || alpha>1
    error('EMA alpha must lie in (0,1].');
end

Tout = Tin;

N = height(Tout);

ema_score = nan(N,1);
reset_score = nan(N,1);
innovation = nan(N,1);
reset_event = false(N,1);

seqs = unique(Tout.sequence_id).';

for is = 1:numel(seqs)
    idx = find(Tout.sequence_id==seqs(is));

    [~,ord] = sort(Tout.line_index(idx));
    idx = idx(ord);

    x = double(Tout.instant_score(idx));
    x = x(:);

    e = nan(size(x));
    r = nan(size(x));
    inn = nan(size(x));
    re = false(size(x));

    e(1) = x(1);
    r(1) = x(1);
    inn(1) = 0;

    for k = 2:numel(x)
        inn(k) = x(k)-e(k-1);

        e(k) = ...
            alpha*x(k) + ...
            (1-alpha)*e(k-1);

        if isfinite(reset_threshold)
            reset_innovation = x(k)-r(k-1);

            if abs(reset_innovation)>reset_threshold
                r(k) = x(k);
                re(k) = true;
            else
                r(k) = ...
                    alpha*x(k) + ...
                    (1-alpha)*r(k-1);
            end
        else
            r(k) = e(k);
        end
    end

    ema_score(idx) = e;
    reset_score(idx) = r;
    innovation(idx) = inn;
    reset_event(idx) = re;
end

Tout.ema_score = ema_score;
Tout.reset_score = reset_score;
Tout.innovation = innovation;
Tout.reset_event = reset_event;

end

