function results = exp09c3b1_signal_level_continuous_state()
%EXP09C3B1_SIGNAL_LEVEL_CONTINUOUS_STATE
% EXP009 / Pilot-01 / Experiment C3-B1
%
% Signal-Level Continuous Azimuth-State Validation
%
% -------------------------------------------------------------------------
% Research question
% -------------------------------------------------------------------------
% C3-A showed, in a bootstrap Markov-state experiment, that:
%
%   persistent latent risk state
%       -> history improves observability
%       -> history improves computation allocation
%       -> abrupt state change causes EMA lag
%       -> innovation reset mitigates that lag.
%
% C3-B1 asks whether the same chain appears when the "state" is no longer
% imposed by a Markov sampler, but is generated by the signal model itself.
%
% -------------------------------------------------------------------------
% Signal-level state
% -------------------------------------------------------------------------
% Across neighboring azimuth lines k:
%
%   A_w/A_s(k)
%   q_s(k)-q_w
%
% vary continuously.
%
% For every line, the complete controlled weak-stage chain is rerun:
%
%   strong LFM + weak LFM + AWGN
%       -> Cheap fixed-notch strong residual
%       -> weak q search
%
% and independently:
%
%   original mixture
%       -> off-grid parametric strong refit
%       -> weak q search.
%
% Thus:
%
%   Beneficial(k,mc)
%   Harmful(k,mc)
%
% are generated from the actual signal-processing chain rather than from
% an imposed state label.
%
% -------------------------------------------------------------------------
% Important controlled boundary
% -------------------------------------------------------------------------
% q_strong is still treated as known/oracle at each line.
%
% This preserves the same weak-stage isolation used in A/B/C1 and prevents
% dominant-q tracking error from being mixed into the C3 history question.
%
% C3-B2 can later replace q_strong by practical estimation/tracking.
%
% -------------------------------------------------------------------------
% Two regimes
% -------------------------------------------------------------------------
% Smooth:
%   continuously varying weak ratio and q separation.
%
% Abrupt:
%   same baseline trajectory, plus one physical parameter jump.
%
% -------------------------------------------------------------------------
% History policies
% -------------------------------------------------------------------------
% InstantPE:
%   percentile risk from Cheap prominence + entropy.
%
% EMA:
%   causal exponential history aggregation.
%
% EMAReset:
%   EMA with innovation-triggered history reset.
%
% PhysicalStatePrior:
%   diagnostic line-level state oracle:
%       score(k) = TRAIN-estimated smoothed
%                  P(Beneficial|k)-P(Harmful|k)
%   It knows line/state, but not the TEST realization fate.
%
% TrialOracle:
%   knows TEST beneficial labels.
%
% -------------------------------------------------------------------------
% Main validation hierarchy
% -------------------------------------------------------------------------
% B1-1:
%   Does continuous physical parameter variation create a reproducible
%   line-dependent fallback-utility state?
%
% B1-2:
%   Does EMA improve observability of that signal-generated state?
%
% B1-3:
%   Does improved state observability improve Beneficial Capture and
%   Weak Recovery at matched computation?
%
% B1-4:
%   Does an abrupt physical-state change create EMA lag, and does reset
%   reduce that transition error?
%
% Run:
%   results = exp09c3b1_signal_level_continuous_state;

cfg = config_exp09c3b1();

%% Resolve paths
this_file = mfilename('fullpath');
this_dir = fileparts(this_file);
code_dir = fileparts(this_dir);
paper_root = fileparts(code_dir);

if isempty(cfg.output_dir)
    out_dir = fullfile(paper_root,'results','exp09_pilot01', ...
        'exp09c3b1_signal_level_continuous_state');
else
    out_dir = cfg.output_dir;
end

if ~exist(out_dir,'dir')
    mkdir(out_dir);
end

fprintf('\n============================================================\n');
fprintf(' EXP009-C3-B1 / Signal-Level Continuous State Validation\n');
fprintf('============================================================\n');
fprintf('Output: %s\n',out_dir);
fprintf('Lines/sequence: %d\n',cfg.num_lines);
fprintf('Train MC/regime: %d\n',cfg.num_train_mc);
fprintf('Test  MC/regime: %d\n',cfg.num_test_mc);
fprintf('SNR: %.1f dB\n\n',cfg.snr_db);

%% Common signal/search setup
N = cfg.N;
n = 0:N-1;
t = (n-N/2)/N;

q_search = cfg.q_search_min:cfg.q_search_step:cfg.q_search_max;
D_search = build_dechirp_dictionary(q_search,t,cfg);

%% Build physical trajectories
traj_smooth = build_trajectory("Smooth",cfg);
traj_abrupt = build_trajectory("Abrupt",cfg);

writetable(traj_smooth, ...
    fullfile(out_dir,'trajectory_smooth.csv'));

writetable(traj_abrupt, ...
    fullfile(out_dir,'trajectory_abrupt.csv'));

%% Precompute deterministic signal components for each regime
det_smooth = precompute_deterministic_chain( ...
    traj_smooth,t,cfg);

det_abrupt = precompute_deterministic_chain( ...
    traj_abrupt,t,cfg);

%% Generate TRAIN signal-level banks
rng(cfg.seed,'twister');

tic;
train_smooth = run_signal_mc_bank( ...
    det_smooth,traj_smooth,cfg.num_train_mc, ...
    cfg.seed+100,D_search,q_search,t,cfg);
time_train_smooth = toc;

tic;
train_abrupt = run_signal_mc_bank( ...
    det_abrupt,traj_abrupt,cfg.num_train_mc, ...
    cfg.seed+200,D_search,q_search,t,cfg);
time_train_abrupt = toc;

%% Generate independent TEST banks
tic;
test_smooth = run_signal_mc_bank( ...
    det_smooth,traj_smooth,cfg.num_test_mc, ...
    cfg.seed+1100,D_search,q_search,t,cfg);
time_test_smooth = toc;

tic;
test_abrupt = run_signal_mc_bank( ...
    det_abrupt,traj_abrupt,cfg.num_test_mc, ...
    cfg.seed+1200,D_search,q_search,t,cfg);
time_test_abrupt = toc;

%% Save raw signal-level trial banks
writetable(train_smooth, ...
    fullfile(out_dir,'train_trials_smooth.csv'));

writetable(train_abrupt, ...
    fullfile(out_dir,'train_trials_abrupt.csv'));

writetable(test_smooth, ...
    fullfile(out_dir,'test_trials_smooth.csv'));

writetable(test_abrupt, ...
    fullfile(out_dir,'test_trials_abrupt.csv'));

%% ------------------------------------------------------------------------
% C3-B1-1: Does physical continuity create a reproducible risk state?
state_smooth = estimate_line_state( ...
    train_smooth,test_smooth,cfg);

state_abrupt = estimate_line_state( ...
    train_abrupt,test_abrupt,cfg);

state_smooth.regime = repmat("Smooth",height(state_smooth),1);
state_abrupt.regime = repmat("Abrupt",height(state_abrupt),1);

state_summary = [state_smooth;state_abrupt];
state_summary = movevars(state_summary,'regime','Before',1);

writetable(state_summary, ...
    fullfile(out_dir,'signal_level_state_summary.csv'));

rho_state_repro_smooth = spearman_manual( ...
    state_smooth.train_utility_smooth, ...
    state_smooth.test_utility_smooth);

rho_state_repro_abrupt = spearman_manual( ...
    state_abrupt.train_utility_smooth, ...
    state_abrupt.test_utility_smooth);

rmse_state_smooth = sqrt(mean( ...
    (state_smooth.train_utility_smooth - ...
     state_smooth.test_utility_smooth).^2));

rmse_state_abrupt = sqrt(mean( ...
    (state_abrupt.train_utility_smooth - ...
     state_abrupt.test_utility_smooth).^2));

if rho_state_repro_smooth < cfg.min_train_test_state_rho_warning
    warning(['Smooth train/test state utility is weakly reproducible ' ...
        '(rho=%.3f). Interpret history results cautiously.'], ...
        rho_state_repro_smooth);
end

if rho_state_repro_abrupt < cfg.min_train_test_state_rho_warning
    warning(['Abrupt train/test state utility is weakly reproducible ' ...
        '(rho=%.3f). Interpret history results cautiously.'], ...
        rho_state_repro_abrupt);
end

%% Attach TRAIN-estimated state targets to all trial banks
[train_smooth,test_smooth] = attach_state_target( ...
    train_smooth,test_smooth,state_smooth);

[train_abrupt,test_abrupt] = attach_state_target( ...
    train_abrupt,test_abrupt,state_abrupt);

%% Instantaneous PE calibration
% Use SMOOTH TRAIN only. Abrupt regime therefore tests generalization
% rather than receiving a separate feature-distribution calibration.
calib = build_instantaneous_calibration(train_smooth);

train_smooth = add_instant_score(train_smooth,calib);
test_smooth  = add_instant_score(test_smooth,calib);

train_abrupt = add_instant_score(train_abrupt,calib);
test_abrupt  = add_instant_score(test_abrupt,calib);

%% ------------------------------------------------------------------------
% Tune EMA alpha on SMOOTH TRAIN only.
alpha_grid = cfg.alpha_grid(:);
alpha_recall = nan(numel(alpha_grid),1);
alpha_state_rho = nan(numel(alpha_grid),1);

for ia = 1:numel(alpha_grid)
    a = alpha_grid(ia);

    T = apply_history(train_smooth,a,NaN);

    alpha_recall(ia) = policy_recall_at_budget( ...
        T,'ema_score',cfg.tune_budget);

    alpha_state_rho(ia) = spearman_manual( ...
        T.ema_score,T.state_utility_norm);
end

[~,best_alpha_idx] = max(alpha_recall);
best_alpha = alpha_grid(best_alpha_idx);

alpha_sweep = table( ...
    alpha_grid,alpha_recall,alpha_state_rho, ...
    'VariableNames',{ ...
    'alpha','train_recall_at_tune_budget', ...
    'train_state_rho'});

writetable(alpha_sweep, ...
    fullfile(out_dir,'alpha_sweep.csv'));

%% Tune reset threshold on ABRUPT TRAIN with alpha fixed.
abrupt_ema_train = apply_history( ...
    train_abrupt,best_alpha,NaN);

innovation_abs = abs(abrupt_ema_train.innovation);
innovation_abs = innovation_abs(isfinite(innovation_abs));

reset_q = cfg.reset_quantile_grid(:);
reset_thr = nan(numel(reset_q),1);
reset_recall = nan(numel(reset_q),1);
reset_jump_error = nan(numel(reset_q),1);

for iq = 1:numel(reset_q)
    thr = empirical_quantile(innovation_abs,reset_q(iq));
    reset_thr(iq) = thr;

    T = apply_history(train_abrupt,best_alpha,thr);

    reset_recall(iq) = policy_recall_at_budget( ...
        T,'reset_score',cfg.tune_budget);

    reset_jump_error(iq) = post_jump_tracking_error( ...
        T,cfg,5);
end

% Primary tuning criterion remains global recovery at the selected budget.
% In exact ties, prefer the smaller post-jump tracking error.
best_reset_idx = select_reset_candidate( ...
    reset_recall,reset_jump_error);

best_reset_quantile = reset_q(best_reset_idx);
best_reset_threshold = reset_thr(best_reset_idx);

reset_sweep = table( ...
    reset_q,reset_thr,reset_recall,reset_jump_error, ...
    'VariableNames',{ ...
    'reset_quantile','reset_threshold', ...
    'train_recall_at_tune_budget', ...
    'train_post_jump_tracking_error'});

writetable(reset_sweep, ...
    fullfile(out_dir,'reset_sweep.csv'));

%% Apply selected history policies
train_smooth = apply_history( ...
    train_smooth,best_alpha,best_reset_threshold);

test_smooth = apply_history( ...
    test_smooth,best_alpha,best_reset_threshold);

train_abrupt = apply_history( ...
    train_abrupt,best_alpha,best_reset_threshold);

test_abrupt = apply_history( ...
    test_abrupt,best_alpha,best_reset_threshold);

%% ------------------------------------------------------------------------
% C3-B1-2: state observability
diag_smooth = state_observability_diagnostics( ...
    train_smooth,test_smooth,"Smooth");

diag_abrupt = state_observability_diagnostics( ...
    train_abrupt,test_abrupt,"Abrupt");

state_diagnostics = [diag_smooth;diag_abrupt];

writetable(state_diagnostics, ...
    fullfile(out_dir,'state_observability_diagnostics.csv'));

%% ------------------------------------------------------------------------
% C3-B1-3: budget allocation
budget_curves = table();

policies = { ...
    'instant_score',"InstantPE"; ...
    'ema_score',"EMA"; ...
    'reset_score',"EMAReset"; ...
    'state_prior_score',"PhysicalStatePrior"};

regimes = ["Smooth","Abrupt"];
train_sets = {train_smooth,train_abrupt};
test_sets  = {test_smooth,test_abrupt};

for ir = 1:2
    Ttr = train_sets{ir};
    Tte = test_sets{ir};

    for ip = 1:size(policies,1)
        C = evaluate_score_policy_curve( ...
            Ttr,Tte,policies{ip,1},cfg.budget_grid);

        C.regime = repmat(regimes(ir),height(C),1);
        C.policy = repmat(policies{ip,2},height(C),1);

        budget_curves = [budget_curves;C]; %#ok<AGROW>
    end

    Cto = trial_oracle_curve(Tte,cfg.budget_grid);
    Cto.regime = repmat(regimes(ir),height(Cto),1);
    Cto.policy = repmat("TrialOracle",height(Cto),1);

    Cr = random_expected_curve(Tte,cfg.budget_grid);
    Cr.regime = repmat(regimes(ir),height(Cr),1);
    Cr.policy = repmat("RandomExpected",height(Cr),1);

    budget_curves = [budget_curves;Cto;Cr]; %#ok<AGROW>
end

budget_curves = movevars( ...
    budget_curves,{'regime','policy'},'Before',1);

writetable(budget_curves, ...
    fullfile(out_dir,'signal_level_budget_curves.csv'));

%% Highlighted operating points
point_rows = {};

for ir = 1:2
    regime = regimes(ir);
    Creg = budget_curves(budget_curves.regime==regime,:);

    pols = unique(Creg.policy,'stable');

    for ip = 1:numel(pols)
        Cp = Creg(Creg.policy==pols(ip),:);

        for ib = 1:numel(cfg.report_budgets)
            b = cfg.report_budgets(ib);
            [~,ii] = min(abs(Cp.target_budget-b));

            point_rows(end+1,:) = { ... %#ok<AGROW>
                char(regime),char(pols(ip)),b, ...
                Cp.actual_trigger_rate(ii), ...
                Cp.policy_recall(ii), ...
                Cp.beneficial_capture(ii), ...
                Cp.benefit_precision(ii), ...
                Cp.harmful_fraction_among_triggers(ii), ...
                Cp.normalized_q_search_budget(ii)};
        end
    end
end

budget_points = cell2table(point_rows, ...
    'VariableNames',{ ...
    'regime','policy','target_budget','actual_trigger_rate', ...
    'policy_recall','beneficial_capture','benefit_precision', ...
    'harmful_fraction_among_triggers', ...
    'normalized_q_search_budget'});

writetable(budget_points, ...
    fullfile(out_dir,'reported_budget_points.csv'));

%% ------------------------------------------------------------------------
% C3-B1-4: abrupt-transition diagnostics
jump_line = traj_abrupt.line_index( ...
    traj_abrupt.is_jump_start);

% Robust physical-jump utility change: compare short TRAIN windows before
% and after the jump rather than adjacent smoothed samples.
jpre = max(1,jump_line-5):(jump_line-1);
jpost = jump_line:min(cfg.num_lines,jump_line+4);

jump_state_change = abs( ...
    mean(state_abrupt.train_utility_raw(jpost),'omitnan') - ...
    mean(state_abrupt.train_utility_raw(jpre),'omitnan'));

if jump_state_change < cfg.min_jump_utility_change_warning
    warning(['The chosen physical parameter jump generated only a small ' ...
        'TRAIN utility change (%.3f). Reset results may be inconclusive.'], ...
        jump_state_change);
end

jump_diag = jump_diagnostics( ...
    test_abrupt,cfg,5);

writetable(jump_diag, ...
    fullfile(out_dir,'jump_tracking_diagnostics.csv'));

%% Runtime summary
runtime_summary = table( ...
    ["TrainSmooth";"TrainAbrupt";"TestSmooth";"TestAbrupt"], ...
    [time_train_smooth;time_train_abrupt; ...
     time_test_smooth;time_test_abrupt], ...
    'VariableNames',{'bank','runtime_seconds'});

writetable(runtime_summary, ...
    fullfile(out_dir,'runtime_summary.csv'));

%% Save representative TEST sequence
rep_smooth = test_smooth(test_smooth.sequence_id==1,:);
rep_abrupt = test_abrupt(test_abrupt.sequence_id==1,:);

writetable(rep_smooth, ...
    fullfile(out_dir,'representative_smooth_sequence.csv'));

writetable(rep_abrupt, ...
    fullfile(out_dir,'representative_abrupt_sequence.csv'));

%% Console summary
fprintf('================ C3-B1 STATE REPRODUCIBILITY ================\n');
fprintf('Smooth train/test utility rho = %.3f, RMSE = %.4f\n', ...
    rho_state_repro_smooth,rmse_state_smooth);
fprintf('Abrupt train/test utility rho = %.3f, RMSE = %.4f\n', ...
    rho_state_repro_abrupt,rmse_state_abrupt);

fprintf('\n================ C3-B1 TUNING ================================\n');
fprintf('Best EMA alpha        = %.3f\n',best_alpha);
fprintf('Best reset quantile   = %.3f\n',best_reset_quantile);
fprintf('Best reset threshold  = %.6f\n',best_reset_threshold);
fprintf('Jump line             = %d\n',jump_line);
fprintf('TRAIN utility jump    = %.4f\n',jump_state_change);

fprintf('\n================ C3-B1 STATE OBSERVABILITY ==================\n');
for i = 1:height(state_diagnostics)
    fprintf(['%-7s %-20s rho_trial=%.3f rho_lineMean=%.3f ' ...
        'AUC(B)=%.3f\n'], ...
        state_diagnostics.regime{i}, ...
        state_diagnostics.policy{i}, ...
        state_diagnostics.trial_level_state_rho(i), ...
        state_diagnostics.line_mean_state_rho(i), ...
        state_diagnostics.beneficial_auc(i));
end

fprintf('\n================ C3-B1 25%% BUDGET ===========================\n');
rows25 = budget_points(abs(budget_points.target_budget-0.25)<1e-12,:);

for i = 1:height(rows25)
    fprintf(['%-7s %-20s actual=%.3f recall=%.3f ' ...
        'capture=%.3f precision=%.3f harm=%.3f\n'], ...
        rows25.regime{i},rows25.policy{i}, ...
        rows25.actual_trigger_rate(i), ...
        rows25.policy_recall(i), ...
        rows25.beneficial_capture(i), ...
        rows25.benefit_precision(i), ...
        rows25.harmful_fraction_among_triggers(i));
