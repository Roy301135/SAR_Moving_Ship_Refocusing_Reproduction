fprintf(fid,'State reproducibility\n');
fprintf(fid,'---------------------\n');
fprintf(fid,'Smooth train/test utility rho: %.6f\n',rho_state_repro_smooth);
fprintf(fid,'Smooth train/test utility RMSE: %.6f\n',rmse_state_smooth);
