best = max(recall_vec);

tol = max(1e-12,1e-9*max(1,abs(best)));

cand = find(abs(recall_vec-best)<=tol);

if isempty(cand)
    [~,idx] = max(recall_vec);
    return;
end

if numel(cand)==1
    idx = cand;
    return;
end

[~,jj] = min(error_vec(cand));
idx = cand(jj);

end

