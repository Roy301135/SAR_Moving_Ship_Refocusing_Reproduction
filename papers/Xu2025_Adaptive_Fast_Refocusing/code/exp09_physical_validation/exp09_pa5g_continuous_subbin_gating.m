end

%% ========================================================================
function eta_hat = ...
    estimate_log_parabolic(x,a,cfg)
% PA5F estimator retained only for bias comparison.

if ~strcmpi(cfg.old_subbin_estimator, ...
        'LogPowerParabolic3')
    error('Unknown old estimator: %s', ...
        cfg.old_subbin_estimator);
end

Y = matched_lfm_transform(x,a);
P = abs(Y).^2;

N = numel(P);
[~,i0] = max(P);

im = mod(i0-2,N)+1;
ip = mod(i0,N)+1;

pmax = max(P);

Lm = log(max(P(im), ...
    cfg.log_power_floor*pmax));

L0 = log(max(P(i0), ...
    cfg.log_power_floor*pmax));

Lp = log(max(P(ip), ...
    cfg.log_power_floor*pmax));

den = Lm-2*L0+Lp;

if abs(den)<=100*eps(max(abs([Lm,L0,Lp])))
    delta = 0;
else
    delta = 0.5*(Lm-Lp)/den;
end

delta = min(max( ...
    delta,-cfg.subbin_delta_clip), ...
    cfg.subbin_delta_clip);

dc = floor(N/2)+1;
k0 = i0-dc;

eta_hat = k0+delta;

end

%% ========================================================================
function [nu_hat,diag] = ...
    estimate_continuous_ml(x,a,cfg)
% Continuous single-tone ML/LS frequency estimate.
%
% Dechirp:
%   z[n] = x[n] exp(-j*pi*a*n^2)
%
% For fixed nu:
%   c_hat = argmin_c ||z-c exp(j2pi nu n/N)||^2
%
% Thus:
%   nu_hat = argmax |sum z exp(-j2pi nu n/N)|^2.

z = dechirp_signal(x,a);

N = numel(z);
m = 0:N-1;

Y = fftshift(fft(z));
[~,i0] = max(abs(Y));

dc = floor(N/2)+1;
k0 = i0-dc;

[nu_hat,Jhat] = ...
    refine_continuous_frequency( ...
        z,m,N,k0,cfg);

Jint = tone_objective(z,m,N,round(nu_hat));

diag = struct();
diag.coarse_integer_bin = k0;
diag.objective_at_hat = Jhat;
diag.objective_at_nearest_integer = Jint;
diag.objective_gain_vs_integer = ...
    (Jhat-Jint)/max(Jhat,cfg.small_norm_floor);

end

%% ========================================================================
function [nu_hat,Jhat] = ...
    refine_continuous_frequency( ...
        z,m,N,center,cfg)

z = z(:).';
m = m(:).';

lb = center-cfg.ml_search_halfwidth_bins;
ub = center+cfg.ml_search_halfwidth_bins;

ng = cfg.ml_bracket_points;

grid = linspace(lb,ub,ng);
J = zeros(size(grid));

for i = 1:ng
    J(i) = tone_objective( ...
        z,m,N,grid(i));
end

[~,ib] = max(J);

i1 = max(1,ib-1);
i2 = min(ng,ib+1);

local_lb = grid(i1);
local_ub = grid(i2);

if local_ub<=local_lb

    nu_hat = grid(ib);
    Jhat = J(ib);
    return;
end

opts = optimset( ...
    'Display','off', ...
    'TolX',cfg.ml_tolx_bins, ...
    'MaxFunEvals',cfg.ml_max_fun_evals);

obj = @(nu) -tone_objective( ...
    z,m,N,nu);

[nu_hat,fval] = fminbnd( ...
    obj,local_lb,local_ub,opts);

Jhat = -fval;

end

%% ========================================================================
function J = tone_objective(z,m,N,nu)

v = exp(-1j*2*pi*nu*m/N);

q = sum(z.*v);

J = abs(q).^2;

end

%% ========================================================================
function [gate,split] = ...
    model_evidence_gate( ...
        x,a,nu_hat,cfg)
% Parameter-free deterministic evidence gate.
%
% H0: nearest integer-bin tone.
% H1: continuous-frequency tone.
%
% Gate:
%   DeltaBIC > 0
%   AND
%   |fractional estimate| > split-aperture disagreement.

z = dechirp_signal(x,a);

N = numel(z);
m = 0:N-1;

nu_int = round(nu_hat);

[rss0,~] = tone_fit_rss( ...
    z,m,N,nu_int);

[rss1,~] = tone_fit_rss( ...
    z,m,N,nu_hat);

energy = real(sum(abs(z).^2));

rss_floor = ...
    cfg.bic_eps_multiplier * ...
    N * eps(max(energy,1));

rss0b = max(rss0,rss_floor);
rss1b = max(rss1,rss_floor);

bic0 = ...
    N*log(rss0b/N) + ...
    cfg.bic_k_integer*log(N);

bic1 = ...
    N*log(rss1b/N) + ...
    cfg.bic_k_continuous*log(N);

delta_bic = bic0-bic1;

split = split_aperture_diagnostic( ...
    z,m,N,nu_hat,cfg);

frac = fractional_component(nu_hat);

bic_prefers = delta_bic>0;

shift_exceeds_split = ...
    abs(frac) > ...
    split.split_inconsistency_bins;

primary_trigger = ...
    bic_prefers && shift_exceeds_split;

gate = struct();
gate.nu_integer_bins = nu_int;
gate.rss_integer = rss0;
gate.rss_continuous = rss1;
gate.bic_integer = bic0;
gate.bic_continuous = bic1;
gate.delta_bic = delta_bic;
gate.bic_prefers_continuous = bic_prefers;

% Mirror split-aperture diagnostics into the gate structure as well.
% This keeps the function interface robust for callers that only retain
% the first output, while the second output remains available when the
% full split diagnostic is needed.
gate.nu_left_bins = split.nu_left_bins;
gate.nu_right_bins = split.nu_right_bins;
gate.split_inconsistency_bins = split.split_inconsistency_bins;

gate.shift_exceeds_split = shift_exceeds_split;
gate.primary_gate_trigger = primary_trigger;

end

%% ========================================================================
function [rss,c_hat] = ...
    tone_fit_rss(z,m,N,nu)

z = z(:).';
m = m(:).';

a = exp(1j*2*pi*nu*m/N);

den = sum(abs(a).^2);

c_hat = ...
    sum(conj(a).*z) / ...
    max(den,eps);

e = z-c_hat*a;

rss = real(sum(abs(e).^2));

end

%% ========================================================================
function S = ...
    split_aperture_diagnostic( ...
        z,m,N,nu_full,cfg)

n = numel(z);

if n<cfg.split_min_samples

    S = struct();
    S.nu_left_bins = NaN;
    S.nu_right_bins = NaN;
    S.split_inconsistency_bins = Inf;
    return;
end

nL = floor(n/2);

idxL = 1:nL;
idxR = (nL+1):n;

[nuL,~] = ...
    refine_continuous_frequency( ...
        z(idxL),m(idxL),N, ...
        nu_full,cfg);

[nuR,~] = ...
    refine_continuous_frequency( ...
        z(idxR),m(idxR),N, ...
        nu_full,cfg);

S = struct();
S.nu_left_bins = nuL;
S.nu_right_bins = nuR;
S.split_inconsistency_bins = ...
    abs(fractional_error(nuL,nuR));

end

%% ========================================================================
function f = fractional_component(nu)
% Fractional displacement relative to nearest integer bin.
% Range is approximately [-0.5,0.5].
%
% At exact +0.5 the sign is numerically ambiguous, but either +0.5 or
% -0.5 moves the tone to an integer bin and is physically equivalent.

f = nu-round(nu);

end

%% ========================================================================
function e = fractional_error(a,b)
% Error modulo one integer DFT bin.

e = mod((a-b)+0.5,1)-0.5;

end

