%% ========================================================================
function run_startup_self_tests(cfg)
% Fail early before the long sweep.

%% Test 1 — continuous estimator on all target offsets
N = 188;
a = 0.001731;

for eta = cfg.fractional_bin_offsets

    x = synth_discrete_lfm( ...
        N,1,a,eta/N,0);

    [ehat,~] = ...
        estimate_continuous_ml(x,a,cfg);

    e = abs(fractional_error(ehat,eta));

    if e>cfg.continuous_solver_rmse_gate_bins
        error('EXP009:PA5G:ContinuousEstimatorSelfTestFailed', ...
            ['Continuous estimator self-test failed at eta=%g. ' ...
             'Error=%g bins.'],eta,e);
    end
end

%% Test 2 — BIC gate must stay OFF for an exact on-grid single tone
x0 = synth_discrete_lfm(N,1,a,0,0);

[e0,~] = estimate_continuous_ml(x0,a,cfg);

[g0,s0diag] = model_evidence_gate( ...
    x0,a,e0,cfg);

% Interface-contract guard: callers may use either the first-output gate
% structure or the second-output split structure. Both must expose the
% split diagnostic explicitly. This prevents field-routing regressions.
required_gate_fields = { ...
    'delta_bic', ...
    'bic_prefers_continuous', ...
    'nu_left_bins', ...
    'nu_right_bins', ...
    'split_inconsistency_bins', ...
    'shift_exceeds_split', ...
    'primary_gate_trigger'};

for ii = 1:numel(required_gate_fields)
    if ~isfield(g0,required_gate_fields{ii})
        error('EXP009:PA5G:GateInterfaceSelfTestFailed', ...
            'Gate output is missing field: %s', ...
            required_gate_fields{ii});
    end
end

required_split_fields = { ...
    'nu_left_bins', ...
    'nu_right_bins', ...
    'split_inconsistency_bins'};

for ii = 1:numel(required_split_fields)
    if ~isfield(s0diag,required_split_fields{ii})
        error('EXP009:PA5G:SplitInterfaceSelfTestFailed', ...
            'Split output is missing field: %s', ...
            required_split_fields{ii});
    end
end

if g0.primary_gate_trigger
    error('EXP009:PA5G:OnGridGateSelfTestFailed', ...
        ['Evidence gate triggered on an exact single on-grid tone. ' ...
         'DeltaBIC=%g, split=%g, frac=%g.'], ...
        g0.delta_bic, ...
        g0.split_inconsistency_bins, ...
        abs(fractional_component(e0)));
end

%% Test 3 — gate must turn ON for an exact strong-only quarter-bin tone
eta1 = 0.25;

x1 = synth_discrete_lfm( ...
    N,1,a,eta1/N,0);

[e1,~] = estimate_continuous_ml(x1,a,cfg);

[g1,~] = model_evidence_gate( ...
    x1,a,e1,cfg);

if ~g1.primary_gate_trigger
    error('EXP009:PA5G:OffGridGateSelfTestFailed', ...
        ['Evidence gate failed on an exact strong-only quarter-bin tone. ' ...
         'DeltaBIC=%g, split=%g, frac=%g.'], ...
        g1.delta_bic, ...
        g1.split_inconsistency_bins, ...
        abs(fractional_component(e1)));
end

end

