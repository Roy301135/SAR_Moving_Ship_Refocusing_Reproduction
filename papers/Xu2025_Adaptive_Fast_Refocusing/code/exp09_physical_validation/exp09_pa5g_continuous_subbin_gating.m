function results = exp09_pa5g_continuous_subbin_gating()
%EXP09_PA5G_CONTINUOUS_SUBBIN_GATING
% EXP009 / PA5G
%
% Continuous Sub-Bin Estimation and Evidence-Gated Recentering
%
% Research questions
% ------------------
% RQ1. Does a continuous single-tone ML/LS estimator eliminate the
%      deterministic intermediate-offset bias of the PA5F log-parabolic
%      estimator?
%
% RQ2. In a coherent strong+weak mixture, how much apparent sub-bin shift
%      remains after replacing interpolation by continuous estimation?
%
% RQ3. Can a data-driven evidence gate suppress the eta=0 false-correction
%      problem without sacrificing the large-off-grid recentering gain?
%
% RQ4. If the gate still fails, is the remaining bottleneck model selection
%      or mixture-induced structured bias?
%
% Continuous estimator
% --------------------
% After true strong dechirping:
%
%   z[n] = A_s exp(j 2 pi nu n/N) + contamination.
%
% For a candidate nu and unknown complex amplitude c:
%
%   c_hat(nu) = arg min_c ||z-c a(nu)||^2
%
% and therefore:
%
%   nu_hat = arg max_nu |a(nu)^H z|^2.
%
% The optimization is continuous. A small deterministic coarse bracket is
% used only to locate the local interval for fminbnd; the final estimate is
% not grid-quantized.
%
% Evidence gate
% -------------
% Integer model H0:
%   nu constrained to nearest integer.
%
% Continuous model H1:
%   nu = continuous ML estimate.
%
% BIC:
%   BIC = N log(RSS/N) + k log N.
%
% The continuous model adds one real frequency parameter.
%
% To reduce mixture-induced false correction, PA5G additionally estimates
% frequency on the first and second aperture halves. Recentering is applied
% only when:
%
%   DeltaBIC = BIC_H0 - BIC_H1 > 0
%
% AND
%
%   |fractional nu_hat| > |nu_hat_left - nu_hat_right|.
%
% Thus the claimed shift must exceed the data's own split-aperture
% disagreement. No physical threshold is tuned.
%
% Groups
% ------
% G0_Baseline
% G1_OracleRecenter
% G2_ContinuousStrongOnly
% G3_ContinuousMixtureAlways
% G4_EvidenceGatedMixture
%
% Isolation
% ---------
% - true strong chirp rate for every group;
% - no noise;
% - no clutter;
% - fixed PlateauAwareTol removal semantics.
%
% Run:
%   results = exp09_pa5g_continuous_subbin_gating;

cfg = config_exp09_pa5g_continuous_subbin_gating();

validate_config_complete(cfg);
run_startup_self_tests(cfg);

%% Output path
this_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(this_dir);
paper_root = fileparts(code_dir);

if isempty(cfg.output_dir)
    out_path = fullfile( ...
        paper_root,'results','exp09_physical_validation', ...
        'exp09_pa5g_continuous_subbin_gating');
else
    out_path = cfg.output_dir;
end

if ~exist(out_path,'dir')
    mkdir(out_path);
end

%% Physical constants
lambda = cfg.c/cfg.fc_hz;
R0 = cfg.platform_height_m*cfg.slant_range_factor;

beamwidth_rad = ...
    cfg.beamwidth_scale * ...
    lambda/cfg.antenna_length_m;

vw = cfg.weak_velocity_mps;

[~,~,Kw] = residual_fm_rates( ...
    vw,R0,lambda,cfg);

aw = Kw/(cfg.prf_hz^2);

%% Apertures
T_paper = cfg.paper_aperture_time_s;
N_paper = max(32,round(cfg.prf_hz*T_paper));

T_beam = ...
    R0*beamwidth_rad/cfg.platform_velocity_mps;
N_beam = max(32,round(cfg.prf_hz*T_beam));

aperture_names = ["Paper1s","BeamDerived"];
N_list = [N_paper,N_beam];

sides = ["LowV","HighV"];

%% =======================================================================
% Track A — strong-only estimator audit
% ========================================================================
est_rows = {};

for ia = 1:numel(aperture_names)

    mode = aperture_names(ia);
    N = N_list(ia);

    for io = 1:numel(cfg.fractional_bin_offsets)

        eta = cfg.fractional_bin_offsets(io);
        b = eta/N;

        for idv = 1:numel(cfg.delta_velocity_mps)

            dv = cfg.delta_velocity_mps(idv);

            for iside = 1:numel(sides)

                side = sides(iside);

                if side=="LowV"
                    vs = vw-dv;
                else
                    vs = vw+dv;
                end

                [~,~,Ks] = residual_fm_rates( ...
                    vs,R0,lambda,cfg);

                as = Ks/(cfg.prf_hz^2);

                s0 = synth_discrete_lfm( ...
                    N,cfg.A_strong,as,b,0);

                eta_old = estimate_log_parabolic( ...
                    s0,as,cfg);

                [eta_ml,ml_diag] = ...
                    estimate_continuous_ml( ...
                        s0,as,cfg);

                err_old = fractional_error( ...
                    eta_old,eta);

                err_ml = fractional_error( ...
                    eta_ml,eta);

                [gate_diag,~] = ...
                    model_evidence_gate( ...
                        s0,as,eta_ml,cfg);

                est_rows(end+1,:) = { ... %#ok<AGROW>
                    char(mode),N,eta,dv,char(side),vs, ...
                    eta_old,err_old, ...
                    eta_ml,err_ml, ...
                    ml_diag.coarse_integer_bin, ...
                    ml_diag.objective_gain_vs_integer, ...
                    gate_diag.delta_bic, ...
                    gate_diag.split_inconsistency_bins, ...
                    double(gate_diag.bic_prefers_continuous), ...
                    double(gate_diag.primary_gate_trigger)};
            end
        end
    end
end

estimator_trials = cell2table(est_rows, ...
    'VariableNames',{ ...
    'aperture_mode','azimuth_samples', ...
    'true_eta_bins','delta_velocity_mps', ...
    'strong_velocity_side','strong_velocity_mps', ...
    'old_parabolic_eta_hat_bins', ...
    'old_parabolic_eta_error_bins', ...
    'continuous_ml_eta_hat_bins', ...
    'continuous_ml_eta_error_bins', ...
    'coarse_integer_bin', ...
    'continuous_objective_gain_vs_integer', ...
    'delta_bic', ...
    'split_inconsistency_bins', ...
    'bic_prefers_continuous', ...
    'primary_gate_trigger'});

writetable(estimator_trials, ...
    fullfile(out_path,'pa5g_strongonly_estimator_trials.csv'));

estimator_summary = ...
    summarize_strongonly_estimators( ...
        estimator_trials);

writetable(estimator_summary, ...
    fullfile(out_path,'pa5g_strongonly_estimator_summary.csv'));

%% =======================================================================
% Track B — zero-mismatch floor audit with continuous strong-only estimate
% ========================================================================
floor_groups = [ ...
    "G0_Baseline", ...
    "G1_OracleRecenter", ...
    "G2_ContinuousStrongOnly"];

floor_rows = {};

for ia = 1:numel(aperture_names)

    mode = aperture_names(ia);
    N = N_list(ia);

    for io = 1:numel(cfg.fractional_bin_offsets)

        eta = cfg.fractional_bin_offsets(io);
        b = eta/N;

        for idv = 1:numel(cfg.delta_velocity_mps)

            dv = cfg.delta_velocity_mps(idv);

            for iside = 1:numel(sides)

                side = sides(iside);

                if side=="LowV"
                    vs = vw-dv;
                else
                    vs = vw+dv;
                end

                [~,~,Ks] = residual_fm_rates( ...
                    vs,R0,lambda,cfg);

                as = Ks/(cfg.prf_hz^2);

                s0 = synth_discrete_lfm( ...
                    N,cfg.A_strong,as,b,0);

                w0 = synth_discrete_lfm( ...
                    N,1,aw,b,0);

                [eta_ml,~] = ...
                    estimate_continuous_ml( ...
                        s0,as,cfg);

                eta_ml_frac = fractional_component(eta_ml);

                eta_used_values = [ ...
                    0, ...
                    eta, ...
                    eta_ml_frac];

                for ig = 1:numel(floor_groups)

                    group = floor_groups(ig);
                    eta_used = eta_used_values(ig);

                    [s_rec,~] = recenter_signal( ...
                        s0,eta_used);

                    [w_rec,~] = recenter_signal( ...
                        w0,eta_used);

                    Ys = matched_lfm_transform( ...
                        s_rec,as);

                    for il = 1:numel( ...
                            cfg.filter_window_length_bins)

                        Lwin = ...
                            cfg.filter_window_length_bins(il);

                        [mask,mask_info] = ...
                            build_plateau_tol_mask( ...
                                Ys,Lwin,cfg);

                        [sr,wr] = ...
                            apply_fixed_mask_components( ...
                                s_rec,w_rec,as,mask);

                        L0 = ...
                            norm(sr) / ...
                            max(norm(s_rec), ...
                                cfg.small_norm_floor);

                        D0 = ...
                            norm(wr) / ...
                            max(norm(w_rec), ...
                                cfg.small_norm_floor);

                        rmin = ...
                            recoverability_floor(L0,D0);

                        floor_rows(end+1,:) = { ... %#ok<AGROW>
                            char(mode),N,eta,dv, ...
                            char(side),vs,char(group), ...
                            eta_used, ...
                            fractional_error(eta_used,eta), ...
                            Lwin,L0,D0,rmin, ...
                            mask_info.mask_bin_count};
                    end
                end
            end
        end
    end
end

floor_trials = cell2table(floor_rows, ...
    'VariableNames',{ ...
    'aperture_mode','azimuth_samples', ...
    'true_eta_bins','delta_velocity_mps', ...
    'strong_velocity_side','strong_velocity_mps', ...
    'group','eta_used_bins', ...
    'eta_used_error_bins','window_bins', ...
    'zero_mismatch_strong_leak_L0', ...
    'zero_mismatch_weak_loss_D0', ...
    'recoverability_floor_rmin', ...
    'mask_bin_count'});

writetable(floor_trials, ...
    fullfile(out_path,'pa5g_floor_trials.csv'));

floor_summary = summarize_floor(floor_trials);

writetable(floor_summary, ...
    fullfile(out_path,'pa5g_floor_summary.csv'));

best_floor_summary = ...
    summarize_best_floor(floor_summary);

writetable(best_floor_summary, ...
    fullfile(out_path,'pa5g_best_floor_summary.csv'));

%% =======================================================================
% Track C — practical coherent-mixture gating audit
% ========================================================================
groups = [ ...
    "G0_Baseline", ...
    "G1_OracleRecenter", ...
    "G2_ContinuousStrongOnly", ...
    "G3_ContinuousMixtureAlways", ...
    "G4_EvidenceGatedMixture"];

trial_rows = {};
gate_rows = {};

for ia = 1:numel(aperture_names)

    mode = aperture_names(ia);
    N = N_list(ia);

    for io = 1:numel(cfg.fractional_bin_offsets)

        eta = cfg.fractional_bin_offsets(io);
        b = eta/N;

        for idv = 1:numel(cfg.delta_velocity_mps)

            dv = cfg.delta_velocity_mps(idv);

            for iside = 1:numel(sides)

                side = sides(iside);

                if side=="LowV"
                    vs = vw-dv;
                else
                    vs = vw+dv;
                end

                [~,~,Ks] = residual_fm_rates( ...
                    vs,R0,lambda,cfg);

                as = Ks/(cfg.prf_hz^2);

                s0 = synth_discrete_lfm( ...
                    N,cfg.A_strong,as,b,0);

                w_unit = synth_discrete_lfm( ...
                    N,1,aw,b,0);

                [eta_g2_abs,~] = ...
                    estimate_continuous_ml( ...
                        s0,as,cfg);

                eta_g2 = ...
                    fractional_component(eta_g2_abs);

                for ir = 1:numel( ...
                        cfg.weak_to_strong_ratio)

                    rA = cfg.weak_to_strong_ratio(ir);

                    for ip = 1:numel( ...
                            cfg.relative_phase_rad)

                        phi = cfg.relative_phase_rad(ip);

                        w_true = ...
                            rA*exp(1j*phi)*w_unit;

                        x = s0+w_true;

                        [eta_mix_abs,mix_ml_diag] = ...
                            estimate_continuous_ml( ...
                                x,as,cfg);

                        eta_mix = ...
                            fractional_component(eta_mix_abs);

                        [gate_diag,split_diag] = ...
                            model_evidence_gate( ...
                                x,as,eta_mix_abs,cfg);

                        if gate_diag.primary_gate_trigger
                            eta_g4 = eta_mix;
                        else
                            eta_g4 = 0;
                        end

                        eta_used_values = [ ...
                            0, ...
                            eta, ...
                            eta_g2, ...
                            eta_mix, ...
                            eta_g4];

                        gate_rows(end+1,:) = { ... %#ok<AGROW>
                            char(mode),N,eta,dv, ...
                            char(side),vs,rA,phi, ...
                            eta_mix_abs,eta_mix, ...
                            fractional_error(eta_mix,eta), ...
                            mix_ml_diag.objective_gain_vs_integer, ...
                            gate_diag.nu_integer_bins, ...
                            gate_diag.rss_integer, ...
                            gate_diag.rss_continuous, ...
                            gate_diag.delta_bic, ...
                            double(gate_diag.bic_prefers_continuous), ...
                            split_diag.nu_left_bins, ...
                            split_diag.nu_right_bins, ...
                            split_diag.split_inconsistency_bins, ...
                            abs(eta_mix), ...
                            double(gate_diag.shift_exceeds_split), ...
                            double(gate_diag.primary_gate_trigger)};

                        for ig = 1:numel(groups)

                            group = groups(ig);
                            eta_used = eta_used_values(ig);

                            [x_rec,~] = ...
                                recenter_signal( ...
                                    x,eta_used);

                            [s_rec,~] = ...
                                recenter_signal( ...
                                    s0,eta_used);

                            [w_rec,~] = ...
                                recenter_signal( ...
                                    w_true,eta_used);

                            Yx = matched_lfm_transform( ...
                                x_rec,as);

                            for il = 1:numel( ...
                                    cfg.filter_window_length_bins)

                                Lwin = ...
                                    cfg.filter_window_length_bins(il);

                                [mask,mask_info] = ...
                                    build_plateau_tol_mask( ...
                                        Yx,Lwin,cfg);

                                residual = ...
                                    remove_with_mask( ...
                                        x_rec,as,mask);

                                E = ...
                                    norm(residual-w_rec) / ...
                                    max(norm(w_rec), ...
                                        cfg.small_norm_floor);

                                [sr,wr] = ...
                                    apply_fixed_mask_components( ...
                                        s_rec,w_rec,as,mask);

                                Ls = ...
                                    norm(sr) / ...
                                    max(norm(s_rec), ...
                                        cfg.small_norm_floor);

                                Dw = ...
                                    norm(wr) / ...
                                    max(norm(w_rec), ...
                                        cfg.small_norm_floor);

                                Epred = sqrt( ...
                                    (Ls/rA)^2 + Dw^2);

                                identity_err = ...
                                    abs(E-Epred);

                                bweak_after = ...
                                    (eta-eta_used)/N;

                                [weak_ok,weak_ratio] = ...
                                    weak_stage_readiness( ...
                                        residual,aw, ...
                                        bweak_after,cfg);

                                trial_rows(end+1,:) = { ... %#ok<AGROW>
                                    char(mode),N,eta,dv, ...
                                    char(side),vs,rA,phi, ...
                                    char(group), ...
                                    eta_used, ...
                                    fractional_error( ...
                                        eta_used,eta), ...
                                    double(gate_diag.primary_gate_trigger), ...
                                    gate_diag.delta_bic, ...
                                    split_diag.split_inconsistency_bins, ...
                                    Lwin,E, ...
                                    double(E<= ...
                                        cfg.error_feasible_threshold), ...
                                    double(weak_ok), ...
                                    weak_ratio,Ls,Dw,Epred, ...
                                    identity_err, ...
                                    mask_info.mask_bin_count};
                            end
                        end
                    end
                end
            end
        end
    end
end

gate_trials = cell2table(gate_rows, ...
    'VariableNames',{ ...
    'aperture_mode','azimuth_samples', ...
    'true_eta_bins','delta_velocity_mps', ...
    'strong_velocity_side','strong_velocity_mps', ...
    'weak_to_strong_ratio','relative_phase_rad', ...
