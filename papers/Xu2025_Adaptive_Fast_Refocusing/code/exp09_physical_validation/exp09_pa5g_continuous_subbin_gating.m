end

%% ========================================================================
function pk = ...
    plateau_aware_tol(amp,gate,tol)

amp = amp(:).';
N = numel(amp);

pk = [];

if N==1
    pk = 1;
    return;
end

if amp(1)>=amp(2)-tol && ...
        amp(1)>=gate-tol
    pk(end+1) = 1; %#ok<AGROW>
end

for i = 2:N-1

    ge_left = ...
        amp(i)>=amp(i-1)-tol;

    ge_right = ...
        amp(i)>=amp(i+1)-tol;

    strict_somewhere = ...
        amp(i)>amp(i-1)+tol || ...
        amp(i)>amp(i+1)+tol;

    if ge_left && ge_right && ...
            strict_somewhere && ...
            amp(i)>=gate-tol

        pk(end+1) = i; %#ok<AGROW>
    end
end

if amp(N)>=amp(N-1)-tol && ...
        amp(N)>=gate-tol
    pk(end+1) = N; %#ok<AGROW>
end

pk = unique(pk);

if isempty(pk)

    [~,imax] = max(amp);

    pk = find( ...
        abs(amp-amp(imax))<=tol & ...
        amp>=gate-tol);
end

end

