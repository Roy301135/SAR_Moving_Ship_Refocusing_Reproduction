%% ========================================================================
function r = safe_ratio(a,b)

if ~isfinite(a) || ~isfinite(b)
    r = NaN;
elseif abs(b)<=1e-14
    r = double(abs(a)<=1e-14);
else
    r = a/b;
end

end

%% ========================================================================
function D = ...
    build_decision_summary( ...
        ES,GS,BP,IS,cfg)

modes = unique(string(ES.aperture_mode),'stable');

rows = {};

for im = 1:numel(modes)

    mode = modes(im);

    identity_pass = all(IS.identity_gate_pass==1);

    EC = ES( ...
        string(ES.aperture_mode)==mode,:);

    max_cont_rmse = ...
        max(EC.continuous_ml_rmse_bins);

    continuous_solver_pass = ...
        max_cont_rmse <= ...
        cfg.continuous_solver_rmse_gate_bins;

    G0 = GS( ...
        string(GS.aperture_mode)==mode & ...
        abs(GS.true_eta_bins-0)<1e-12,:);

    G5 = GS( ...
        string(GS.aperture_mode)==mode & ...
        abs(GS.true_eta_bins-0.5)<1e-12,:);

    ongrid_bic_trigger = G0.bic_only_trigger_rate(1);
    ongrid_primary_trigger = ...
        G0.primary_gate_trigger_rate(1);

    halfbin_primary_trigger = ...
        G5.primary_gate_trigger_rate(1);

    p0 = pick_best_error( ...
        BP,mode,0,"G0_Baseline");

    p3_0 = pick_best_error( ...
        BP,mode,0,"G3_ContinuousMixtureAlways");

    p4_0 = pick_best_error( ...
        BP,mode,0,"G4_EvidenceGatedMixture");

    p0_half = pick_best_error( ...
        BP,mode,0.5,"G0_Baseline");

    p3_half = pick_best_error( ...
        BP,mode,0.5,"G3_ContinuousMixtureAlways");

    p4_half = pick_best_error( ...
        BP,mode,0.5,"G4_EvidenceGatedMixture");

    gate_suppresses_false_correction = ...
        ongrid_primary_trigger < ...
        ongrid_bic_trigger && ...
        p4_0 <= p3_0;

    gate_retains_offgrid_benefit = ...
        p4_half < p0_half;

    if ~identity_pass

        branch = ...
            "IMPLEMENTATION_IDENTITY_REVIEW";

    elseif ~continuous_solver_pass

        branch = ...
            "CONTINUOUS_ESTIMATOR_NUMERICAL_OR_MODEL_FAILURE";

    elseif gate_suppresses_false_correction && ...
            gate_retains_offgrid_benefit

        branch = ...
            "CONTINUOUS_ESTIMATOR_VALIDATED_AND_EVIDENCE_GATE_PROMISING";

    elseif ~gate_suppresses_false_correction && ...
            gate_retains_offgrid_benefit

        branch = ...
            "CONTINUOUS_ESTIMATOR_WORKS_BUT_FALSE_CORRECTION_GATE_REMAINS_BOTTLENECK";

    elseif gate_suppresses_false_correction && ...
            ~gate_retains_offgrid_benefit

        branch = ...
            "GATE_SUPPRESSES_FALSE_CORRECTION_BUT_IS_TOO_CONSERVATIVE_OFFGRID";

    else

        branch = ...
            "MIXTURE_MODEL_SELECTION_REMAINS_UNRESOLVED";
    end

    rows(end+1,:) = { ... %#ok<AGROW>
        char(mode), ...
        double(identity_pass), ...
        max_cont_rmse, ...
        double(continuous_solver_pass), ...
        ongrid_bic_trigger, ...
        ongrid_primary_trigger, ...
        halfbin_primary_trigger, ...
        p0,p3_0,p4_0, ...
        p0_half,p3_half,p4_half, ...
        double(gate_suppresses_false_correction), ...
        double(gate_retains_offgrid_benefit), ...
        char(branch)};
end

D = cell2table(rows, ...
    'VariableNames',{ ...
    'aperture_mode', ...
    'projection_identity_all_pass', ...
    'maximum_strongonly_continuous_rmse_bins', ...
    'continuous_solver_pass', ...
    'ongrid_bic_only_trigger_rate', ...
    'ongrid_primary_gate_trigger_rate', ...
    'halfbin_primary_gate_trigger_rate', ...
    'ongrid_baseline_min_error', ...
    'ongrid_alwaysMixture_min_error', ...
    'ongrid_gatedMixture_min_error', ...
    'halfbin_baseline_min_error', ...
    'halfbin_alwaysMixture_min_error', ...
    'halfbin_gatedMixture_min_error', ...
    'gate_suppresses_false_correction', ...
    'gate_retains_offgrid_benefit', ...
    'decision_branch'});

end

%% ========================================================================
function q = local_percentile(x,p)

x = sort(x(:));

x = x(isfinite(x));

if isempty(x)
    q = NaN;
    return;
end

if numel(x)==1
    q = x;
    return;
end

r = 1 + (p/100)*(numel(x)-1);

i1 = floor(r);
i2 = ceil(r);

if i1==i2
    q = x(i1);
else
    w = r-i1;
    q = (1-w)*x(i1) + w*x(i2);
end

end

